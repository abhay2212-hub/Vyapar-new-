window.getVyaparProductData = function() {
    const urlParams = new URLSearchParams(window.location.search);
    let id = urlParams.get('id');
    let title = urlParams.get('title');

    if (id && window.VYAPAR_PRODUCTS[id]) {
        return window.VYAPAR_PRODUCTS[id];
    }

    if (title) {
        const titleLower = title.toLowerCase();
        for (let key in window.VYAPAR_PRODUCTS) {
            if (window.VYAPAR_PRODUCTS[key].title.toLowerCase() === titleLower || window.VYAPAR_PRODUCTS[key].id.toLowerCase() === titleLower) {
                return window.VYAPAR_PRODUCTS[key];
            }
        }
    }

    // Default product
    return window.VYAPAR_PRODUCTS["super-shine-laundry-liquid-1l"];
};

